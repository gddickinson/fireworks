def glyph_points(ch: str) -> List[Tuple[int, int]]:
    """Dots of *ch* as (column, row); [] for characters without a glyph."""
    rows = GLYPHS.get(ch.upper(), ())
    return [(c, r) for r, line in enumerate(rows) for c, cell in enumerate(line) if cell == "#"]
